logger = logging.getLogger(__name__)

router = APIRouter(prefix="/api/v1", tags=["RAG Pipeline"])


@router.post("/query", response_model=QueryResponse, summary="Query the RAG system")
async def query_rag(
    request: QueryRequest,
    req: Request,
    pipeline: RAGPipeline = Depends(get_rag_pipeline)
) -> QueryResponse:
    """
    Execute full RAG pipeline:
    - O(1) Redis Query Cache lookup
    - FastEmbed vector generation
    - Qdrant candidate retrieval
    - FlashRank cross-encoder reranking (with RRF fallback)
    - LiteLLM generation (Gemini primary -> Free/Local fallback)
    - Detailed latency metrics tracking
    """
    request_id = getattr(req.state, "request_id", None) or req.headers.get("X-Request-ID") or f"req_{uuid.uuid4().hex[:10]}"
    try:
        return await pipeline.query(request=request, request_id=request_id)
    except Exception as e:
        logger.error("[%s] Query execution error: %s", request_id, str(e), exc_info=True)
        raise HTTPException(status_code=500, detail=f"RAG query execution failed: {str(e)}")


@router.post("/query/stream", summary="Stream RAG response tokens via SSE")
async def stream_query_rag(
    request: QueryRequest,
    req: Request,
    pipeline: RAGPipeline = Depends(get_rag_pipeline)
):
    """
    Stream answer tokens as they are generated by the model.
    Yields data: <token> SSE chunks.
    """
    request_id = getattr(req.state, "request_id", None) or req.headers.get("X-Request-ID") or f"req_{uuid.uuid4().hex[:10]}"

    async def event_generator():
        try:
            async for token in pipeline.stream_query(request=request, request_id=request_id):
                yield f"data: {token}\n\n"
            yield "data: [DONE]\n\n"
        except Exception as e:
            logger.error("[%s] Streaming query error: %s", request_id, str(e))
            yield f"data: [ERROR: {str(e)}]\n\n"

    return StreamingResponse(event_generator(), media_type="text/event-stream")


@router.post("/ingest/text", response_model=IngestResponse, summary="Ingest raw text or markdown")
async def ingest_text(
    request: IngestTextRequest,
    pipeline: RAGPipeline = Depends(get_rag_pipeline)
) -> IngestResponse:
    """
    Ingest text content into the vector database.
    Splits text recursively, checks embedding cache, and indexes in Qdrant.
    """
    try:
        return await pipeline.ingest_document(
            content=request.content,
            document_id=request.document_id,
            metadata=request.metadata,
            collection_name=request.collection_name
        )
    except Exception as e:
        logger.error("Text ingestion error: %s", str(e), exc_info=True)
        raise HTTPException(status_code=500, detail=f"Ingestion failed: {str(e)}")


@router.post("/ingest/file", response_model=IngestResponse, summary="Upload and ingest PDF, TXT, or MD files")
async def ingest_file(
    file: UploadFile = File(..., description="PDF, TXT, or MD file to index"),
    document_id: Optional[str] = Form(None),
    collection_name: Optional[str] = Form(None),
    pipeline: RAGPipeline = Depends(get_rag_pipeline)
) -> IngestResponse:
    """
    Parse uploaded document (PDF or Text), extract text, chunk and index into Qdrant.
    """
    filename = file.filename or "unknown"
    doc_id = document_id or f"file_{uuid.uuid4().hex[:10]}"
    content = ""

    try:
        raw_bytes = await file.read()
        if filename.lower().endswith(".pdf"):
            pdf_reader = pypdf.PdfReader(io.BytesIO(raw_bytes))
            extracted_pages = []
            for page_num, page in enumerate(pdf_reader.pages):
                page_text = page.extract_text() or ""
                if page_text.strip():
                    extracted_pages.append(f"--- Page {page_num + 1} ---\n{page_text}")
            content = "\n\n".join(extracted_pages)
        else:
            # Assume text/markdown/utf-8
            content = raw_bytes.decode("utf-8", errors="replace")

        if not content.strip():
            raise HTTPException(status_code=400, detail="Uploaded file is empty or could not be parsed.")

        metadata = {
            "source_filename": filename,
            "content_type": file.content_type,
            "file_size_bytes": len(raw_bytes)
        }

        return await pipeline.ingest_document(
            content=content,
            document_id=doc_id,
            metadata=metadata,
            collection_name=collection_name
        )
    except HTTPException:
        raise
    except Exception as e:
        logger.error("File ingestion error for '%s': %s", filename, str(e), exc_info=True)
        raise HTTPException(status_code=500, detail=f"File ingestion failed: {str(e)}")


@router.get("/health", response_model=HealthResponse, summary="Check system and services health")
async def health_check(
    cache: CacheService = Depends(get_cache_service),
    vector_db: VectorDBService = Depends(get_vector_db),
    llm: LLMRouterService = Depends(get_llm_router)
) -> HealthResponse:
    """
    Readiness and liveness probe across Redis, Qdrant, and LiteLLM Router.
    """
    services = {}

    # Redis probe
    t0 = time.perf_counter()
    redis_ok = await cache.ping()
    services["redis"] = ServiceStatus(
        healthy=redis_ok,
        details="Connected to Redis server" if redis_ok else "Operating with In-Memory fallback cache (soft-fail)",
        latency_ms=round((time.perf_counter() - t0) * 1000, 2)
    )

    # Qdrant probe
    t1 = time.perf_counter()
    qdrant_ok = vector_db.ping()
    services["qdrant"] = ServiceStatus(
        healthy=qdrant_ok,
        details="Local persistent Qdrant engine" if vector_db._is_local_fallback else "Remote Qdrant cluster",
        latency_ms=round((time.perf_counter() - t1) * 1000, 2)
    )

    # LLM Router probe
    llm_has_keys = llm._has_valid_keys
    services["llm_router"] = ServiceStatus(
        healthy=True,
        details=(
            f"Active (Primary: {settings.PRIMARY_MODEL}, Fallback: {settings.FALLBACK_MODEL})"
            if llm_has_keys
            else "Bootstrapping Mode: Local contextual synthesizer active (provide GEMINI_API_KEY for cloud model)"
        ),
        latency_ms=0.0
    )

    overall_healthy = qdrant_ok
    return HealthResponse(
        status="healthy" if overall_healthy else "degraded",
        environment=settings.ENVIRONMENT,
        services=services
    )


@router.post("/cache/clear", summary="Purge all RAG query and semantic caches")
async def clear_cache(cache: CacheService = Depends(get_cache_service)):
    """Wipe stale cached queries from Redis and memory."""
    await cache.clear_all()
    return {"status": "success", "message": "All query caches cleared successfully."}
